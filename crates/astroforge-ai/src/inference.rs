// ─── NCHW catalog-graph execution (RT-7 slice 2) ────────────────────
//
// Downloaded catalog graphs (SwinIR denoise) consume `[1,3,H,W]`
// float32 RGB in [0,1] with FIXED spatial dims — SwinIR's windowed
// attention is brittle under dynamic H/W in ORT (publisher's card).
// The engine edge-pads each incoming tile up to the fixed size,
// runs, and crops the output back to the tile's real dims; the
// dispatcher's tiler supplies ≤tile-size tiles and cosine-blends
// the overlaps, so seams stay invisible.

/// Convert an F32Image to flat NCHW `[1,C,H,W]` row-major data.
/// Catalog graphs are RGB; other channel counts are an error
/// rather than a silent re-interpretation.
fn f32_image_to_nchw(image: &F32Image) -> Result<(Vec<usize>, Vec<f32>), InferenceError> {
    let (c, h, w) = (image.channels(), image.height(), image.width());
    if c != 3 {
        return Err(InferenceError::BadOutputShape(format!(
            "catalog NCHW graphs expect 3 channels, image has {c}"
        )));
    }
    let mut data = Vec::with_capacity(c * h * w);
    for ch in 0..c {
        for y in 0..h {
            for x in 0..w {
                data.push(image[(ch, y, x)]);
            }
        }
    }
    Ok((vec![1, c, h, w], data))
}

/// Convert flat NCHW output back to an F32Image, validating the
/// shape contract ([1,C,H,W], C == 3, uniform planes).
fn nchw_to_f32_image(shape: &[usize], data: &[f32]) -> Result<F32Image, InferenceError> {
    if shape.len() != 4 || shape[0] != 1 {
        return Err(InferenceError::BadOutputShape(format!(
            "expected [1,C,H,W], got {shape:?}"
        )));
    }
    let (c, h, w) = (shape[1], shape[2], shape[3]);
    if c != 3 {
        return Err(InferenceError::BadOutputShape(format!(
            "expected 3 output channels, got {c}"
        )));
    }
    if data.len() != c * h * w {
        return Err(InferenceError::BadOutputShape(format!(
            "NCHW data length {} does not match shape {shape:?}",
            data.len()
        )));
    }
    let mut image = F32Image::new(w, h, c);
    for ch in 0..c {
        for y in 0..h {
            for x in 0..w {
                image[(ch, y, x)] = data[(ch * h + y) * w + x];
            }
        }
    }
    Ok(image)
}

/// Edge-replicate `tile` up to `size × size` (tiles are always
/// ≤ the fixed graph edge; `size` 0 means the graph is dynamic and
/// the tile passes through untouched).
fn pad_tile_to_nchw_edge(tile: &F32Image, size: u32) -> F32Image {
    let target = size as usize;
    if target == 0 || (tile.width() >= target && tile.height() >= target) {
        return tile.clone();
    }
    let (w, h, c) = (tile.width(), tile.height(), tile.channels());
    let mut out = F32Image::new(target, target, c);
    for ch in 0..c {
        for y in 0..target {
            for x in 0..target {
                let sx = x.min(w - 1);
                let sy = y.min(h - 1);
                out[(ch, y, x)] = tile[(ch, sy, sx)];
            }
        }
    }
    out
}

impl OnnxEngine {
    /// Run a (≤ tile-size) image through a catalog NCHW graph:
    /// pad to the fixed edge, run, crop the output back to the
    /// input dims. The output shape must preserve spatial dims
    /// (denoise-class graphs; SR adapters handle their own scale).
    fn run_nchw_tile(&mut self, tile: &F32Image) -> Result<F32Image, InferenceError> {
        use ort::value::Tensor;
        let EngineMode::Nchw {
            input_name,
            output_name: _,
            tile_size,
        } = self.mode
        else {
            return Err(InferenceError::BadOutputShape(
                "run_nchw_tile on a plane-wise engine".into(),
            ));
        };
        let (w, h, c) = (tile.width(), tile.height(), tile.channels());
        let padded = pad_tile_to_nchw_edge(tile, tile_size);
        let (shape, data) = f32_image_to_nchw(&padded)?;
        let tensor = Tensor::from_array((shape, data.into_boxed_slice()))
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        let outputs = self
            .session
            .run(ort::inputs![input_name => tensor])
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        let (out_shape, out_data) = outputs[0]
            .try_extract_tensor::<f32>()
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        let full = nchw_to_f32_image(
            &out_shape.iter().map(|&d| d as usize).collect::<Vec<_>>(),
            out_data,
        )?;
        if full.width() < w || full.height() < h {
            return Err(InferenceError::BadOutputShape(format!(
                "graph output {}x{} smaller than input tile {w}x{h}",
                full.width(),
                full.height()
            )));
        }
        // Crop the padded margin back off.
        let mut cropped = F32Image::new(w, h, c);
        for ch in 0..c {
            for y in 0..h {
                for x in 0..w {
                    cropped[(ch, y, x)] = full[(ch, y, x)];
                }
            }
        }
        Ok(cropped)
    }

    /// NCHW entry point: images at or under the fixed tile edge run
    /// directly (after padding); larger images are tiled internally
    /// at the fixed edge with the shared tiler + cosine blending.
    fn run_nchw(&mut self, image: &F32Image) -> Result<F32Image, InferenceError> {
        let Some(tile) = self.required_tile_size() else {
            return self.run_nchw_tile(image);
        };
        if image.width() <= tile as usize && image.height() <= tile as usize {
            return self.run_nchw_tile(image);
        }
        let config = crate::tiling::TileConfig {
            tile_size: tile,
            overlap: crate::tiling::DEFAULT_OVERLAP.min(tile / 2),
        };
        let engine_cell = std::cell::RefCell::new(self);
        let first_error: std::cell::RefCell<Option<InferenceError>> = std::cell::RefCell::new(None);
        let result = crate::tiling::run_tiled_inference(image, &config, |tile_img, _geom| {
            if let Some(e) = first_error.borrow().as_ref() {
                let _ = e;
                return tile_img.clone();
            }
            match engine_cell.borrow_mut().run_nchw_tile(tile_img) {
                Ok(out) => out,
                Err(e) => {
                    *first_error.borrow_mut() = Some(e);
                    tile_img.clone()
                }
            }
        });
        if let Some(e) = first_error.into_inner() {
            return Err(e);
        }
        Ok(result)
    }
}

/// Errors from the inference engine. `Ort` carries the ONNX Runtime
/// error string (the `ort` error type does not implement `Clone` /
/// `PartialEq`, so we flatten to `String` at the boundary).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum InferenceError {
    /// The fixture bytes do not match the pinned digest.
    ChecksumMismatch { expected: String, actual: String },
    /// ONNX Runtime refused the model or the run.
    Ort(String),
    /// The graph produced a shape the engine cannot map back to an
    /// image (e.g. inconsistent per-channel output dims).
    BadOutputShape(String),
    /// A required input (mask) was not supplied for this graph kind.
    MissingInput(String),
    /// The catalog model id is not in `CATALOG_MODELS`.
    UnknownCatalogModel(String),
    /// The catalog model is registered but its digest has not
    /// been pinned yet (DP#4 license verification pending). The
    /// engine refuses to load it until a real SHA-256 lands.
    CatalogUnpinned { id: String },
}

impl std::fmt::Display for InferenceError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            InferenceError::ChecksumMismatch { expected, actual } => write!(
                f,
                "model checksum mismatch: expected {expected}, got {actual}"
            ),
            InferenceError::Ort(e) => write!(f, "onnx runtime: {e}"),
            InferenceError::BadOutputShape(s) => write!(f, "bad output shape: {s}"),
            InferenceError::MissingInput(s) => write!(f, "missing input: {s}"),
            InferenceError::UnknownCatalogModel(id) => {
                write!(f, "unknown catalog model: {id}")
            }
            InferenceError::CatalogUnpinned { id } => write!(
                f,
                "catalog model '{id}' is registered but its digest is \
                 not yet pinned (DP#4 license verification pending)"
            ),
        }
    }
}

impl std::error::Error for InferenceError {}

/// One live ONNX session bound to a specific builtin graph kind.
/// Sessions are cheap-ish to build but not free; the dispatcher builds
/// one per apply round. (A session cache keyed by model id is a
/// possible later optimisation — measure first.)
pub struct OnnxEngine {
    session: ort::session::Session,
    kind: BuiltinInputKind,
    /// Execution mode: builtin graphs run plane-wise (one
    /// `[1,1,H,W]` run per channel); downloaded catalog graphs run
    /// NCHW (`[1,3,H,W]` f32 RGB, fixed tile from the download
    /// spec, edge-padded tiles cropped back after the run).
    mode: EngineMode,
}

/// How an open session consumes images (see [`OnnxEngine`]).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum EngineMode {
    PlaneWise(BuiltinInputKind),
    Nchw {
        input_name: &'static str,
        output_name: &'static str,
        /// Fixed spatial tile the graph accepts (0 = dynamic).
        tile_size: u32,
    },
}

impl EngineMode {
    /// The mode for a catalog id, from the download-spec table.
    /// Ids without a downloadable artifact (the builtin shadow
    /// entries) run plane-wise. Pure — no session is opened — so
    /// the routing decision is unit-testable offline.
    pub fn for_catalog(id: &str) -> EngineMode {
        match crate::downloader::download_spec(id) {
            Some(spec) => EngineMode::Nchw {
                input_name: spec.input_name,
                output_name: spec.output_name,
                tile_size: spec.tile_size,
            },
            None => EngineMode::PlaneWise(
                crate::inference::catalog_model(id)
                    .map(|e| e.kind)
                    .unwrap_or(BuiltinInputKind::ImageOnly),
            ),
        }
    }
}

impl OnnxEngine {
    /// Build a session from raw ONNX bytes after verifying the digest
    /// against the pinned value. CPU execution provider only; GPU
    /// providers are compile-time features and land in P5.2.
    pub fn open_verified(
        bytes: &[u8],
        expected_sha256: &str,
        kind: BuiltinInputKind,
    ) -> Result<Self, InferenceError> {
        let actual = ContentStore::sha256_hex(bytes);
        if actual != expected_sha256 {
            return Err(InferenceError::ChecksumMismatch {
                expected: expected_sha256.to_string(),
                actual,
            });
        }
        let session = ort::session::Session::builder()
            .and_then(|mut b| b.commit_from_memory(bytes))
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        Ok(Self {
            session,
            kind,
            mode: EngineMode::PlaneWise(kind),
        })
    }

    pub fn open_builtin(model: &'static BuiltinModel) -> Result<Self, InferenceError> {
        Self::open_verified(model.bytes, model.sha256, model.kind)
    }

    /// Open a session from a downloaded catalog artifact. The
    /// `id` is looked up in [`CATALOG_MODELS`]; the runtime
    /// digest of `bytes` is verified against the pinned value;
    /// the engine fails closed on unknown id or unpinned entry.
    ///
    /// This closes DP#4: prior to this slice, catalog digests
    /// were placeholders and the engine accepted any bytes.
    pub fn open_catalog(id: &str, bytes: Vec<u8>) -> Result<Self, InferenceError> {
        let entry =
            catalog_model(id).ok_or_else(|| InferenceError::UnknownCatalogModel(id.to_string()))?;
        if entry.sha256 == UNVERIFIED_SHA256 {
            return Err(InferenceError::CatalogUnpinned { id: id.to_string() });
        }
        let actual = ContentStore::sha256_hex(&bytes);
        if actual != entry.sha256 {
            return Err(InferenceError::ChecksumMismatch {
                expected: entry.sha256.to_string(),
                actual,
            });
        }
        let kind = entry.kind;
        let mode = EngineMode::for_catalog(id);
        let session = ort::session::Session::builder()
            .and_then(|mut b| b.commit_from_memory(&bytes))
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        Ok(Self {
            session,
            kind,
            mode,
        })
    }

    /// Open a session from arbitrary catalog bytes without a
    /// registry check. Used by tests that construct synthetic
    /// inputs and by legacy catalog paths that have not yet
    /// migrated to the pinned [`open_catalog`] entry point.
    ///
    /// **Pre-DP#4 callers only.** Production paths should use
    /// [`open_catalog`] which verifies the digest.
    pub fn open_catalog_unpinned(
        bytes: Vec<u8>,
        kind: BuiltinInputKind,
    ) -> Result<Self, InferenceError> {
        let session = ort::session::Session::builder()
            .and_then(|mut b| b.commit_from_memory(&bytes))
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        Ok(Self {
            session,
            kind,
            mode: EngineMode::PlaneWise(kind),
        })
    }

    pub fn kind(&self) -> BuiltinInputKind {
        self.kind
    }

    pub fn mode(&self) -> EngineMode {
        self.mode
    }

    /// The fixed spatial tile this engine requires, when the graph
    /// has hard-coded spatial dims (catalog NCHW graphs). The
    /// dispatcher must tile at exactly this size; `None` lets the
    /// caller pick (builtin graphs are dynamic).
    pub fn required_tile_size(&self) -> Option<u32> {
        match self.mode {
            EngineMode::Nchw { tile_size, .. } if tile_size > 0 => Some(tile_size),
            _ => None,
        }
    }

    /// Run the graph over every channel of `image` and restack the
    /// per-channel outputs. `strength` feeds the `strength` /
    /// `threshold` scalar input when the graph kind declares one;
    /// `mask` feeds the `mask` tensor input for masked-fill.
    ///
    /// Output dims come from the graph (the upscale graph returns
    /// `[1, 1, 2H, 2W]`); all channels must agree.
    pub fn run(
        &mut self,
        image: &F32Image,
        strength: Option<f32>,
        mask: Option<&Mask>,
    ) -> Result<F32Image, InferenceError> {
        if let EngineMode::Nchw { .. } = self.mode {
            return self.run_nchw(image);
        }
        let channels = image.channels();
        let mut out_planes: Option<(usize, usize, Vec<Vec<f32>>)> = None;
        for c in 0..channels {
            let plane = extract_plane(image, c);
            let out = self.run_plane(image.width(), image.height(), &plane, strength, mask)?;
            match &mut out_planes {
                None => out_planes = Some((out.0, out.1, vec![out.2])),
                Some((w, h, planes)) => {
                    if *w != out.0 || *h != out.1 {
                        return Err(InferenceError::BadOutputShape(format!(
                            "channel {c} produced {}x{}, expected {w}x{h}",
                            out.0, out.1
                        )));
                    }
                    planes.push(out.2);
                }
            }
        }
        let (w, h, planes) = out_planes
            .ok_or_else(|| InferenceError::BadOutputShape("image has zero channels".into()))?;
        Ok(stack_planes(w, h, &planes))
    }

    /// Run one single-channel plane through the graph. Returns
    /// `(out_w, out_h, row-major pixels)`.
    fn run_plane(
        &mut self,
        width: usize,
        height: usize,
        plane: &[f32],
        strength: Option<f32>,
        mask: Option<&Mask>,
    ) -> Result<(usize, usize, Vec<f32>), InferenceError> {
        use ort::value::Tensor;

        let img_tensor = Tensor::from_array((
            vec![1usize, 1, height, width],
            plane.to_vec().into_boxed_slice(),
        ))
        .map_err(|e| InferenceError::Ort(e.to_string()))?;

        let outputs = match self.kind {
            BuiltinInputKind::ImageOnly => self
                .session
                .run(ort::inputs![img_tensor])
                .map_err(|e| InferenceError::Ort(e.to_string()))?,
            BuiltinInputKind::Strength | BuiltinInputKind::Threshold => {
                let name = match self.kind {
                    BuiltinInputKind::Strength => "strength",
                    _ => "threshold",
                };
                let value = strength.unwrap_or(0.5);
                let scalar = Tensor::from_array((vec![1usize], vec![value].into_boxed_slice()))
                    .map_err(|e| InferenceError::Ort(e.to_string()))?;
                self.session
                    .run(ort::inputs!["image" => img_tensor, name => scalar])
                    .map_err(|e| InferenceError::Ort(e.to_string()))?
            }
            BuiltinInputKind::Mask => {
                let mask = mask.ok_or_else(|| {
                    InferenceError::MissingInput("masked-fill graph requires a mask tensor".into())
                })?;
                let mask_plane = mask_plane_for(mask, width, height);
                let mask_tensor = Tensor::from_array((
                    vec![1usize, 1, height, width],
                    mask_plane.into_boxed_slice(),
                ))
                .map_err(|e| InferenceError::Ort(e.to_string()))?;
                self.session
                    .run(ort::inputs!["image" => img_tensor, "mask" => mask_tensor])
                    .map_err(|e| InferenceError::Ort(e.to_string()))?
            }
        };

        let (shape, data) = outputs[0]
            .try_extract_tensor::<f32>()
            .map_err(|e| InferenceError::Ort(e.to_string()))?;
        let dims: Vec<usize> = shape.iter().map(|&d| d as usize).collect();
        if dims.len() != 4 || dims[0] != 1 || dims[1] != 1 {
            return Err(InferenceError::BadOutputShape(format!(
                "expected [1,1,H,W], got {dims:?}"
            )));
        }
        Ok((dims[3], dims[2], data.to_vec()))
    }
}

/// Extract channel `c` of an F32Image as a row-major `Vec<f32>`.
fn extract_plane(image: &F32Image, c: usize) -> Vec<f32> {
    let w = image.width();
    let h = image.height();
    let mut plane = Vec::with_capacity(w * h);
    for y in 0..h {
        for x in 0..w {
            plane.push(image[(c, y, x)]);
        }
    }
    plane
}

/// Restack per-channel row-major planes into an F32Image
/// (`(C, H, W)` layout).
fn stack_planes(width: usize, height: usize, planes: &[Vec<f32>]) -> F32Image {
    let mut img = F32Image::new(width, height, planes.len());
    for (c, plane) in planes.iter().enumerate() {
        for y in 0..height {
            for x in 0..width {
                img[(c, y, x)] = plane[y * width + x];
            }
        }
    }
    img
}

/// Rasterise a mask into a `width * height` row-major plane, sampling
/// with clamping when the mask dims disagree with the image dims (a
/// mask authored against a downscaled preview still applies).
fn mask_plane_for(mask: &Mask, width: usize, height: usize) -> Vec<f32> {
    let mut plane = Vec::with_capacity(width * height);
    for y in 0..height {
        for x in 0..width {
            let mx = (x as u64 * mask.width as u64 / width.max(1) as u64) as u32;
            let my = (y as u64 * mask.height as u64 / height.max(1) as u64) as u32;
            plane.push(mask.get(mx.min(mask.width - 1), my.min(mask.height - 1)));
        }
    }
    plane
}

/// A process-wide cache of `OnnxEngine` sessions keyed by model
/// identity. Building a session is cheap (a few hundred
/// milliseconds), but a 50-image apply round on the same model
/// ends up paying that cost 50 times. Caching by `(kind,
/// sha256)` cuts the per-apply cost to one session build per
/// model lifetime.
///
/// Concurrency: `Arc<Mutex<HashMap<...>>>` lets the dispatcher
/// share the cache across threads. The mutex is uncontended in
/// the steady state (cache hits don't write). The cache is
/// append-only within a session — no eviction today; future
/// work can add a TTL if memory pressure warrants.
///
/// The cache stores `Arc<Mutex<OnnxEngine>>` rather than
/// `Arc<OnnxEngine>` because `Session::run` takes `&mut self`
/// in the current `ort` API; sharing requires interior
/// mutability. Each cache hit locks the engine briefly for the
/// duration of one `run`.
#[derive(Default, Clone)]
pub struct SessionCache {
    inner: Arc<Mutex<HashMap<String, Arc<Mutex<OnnxEngine>>>>>,
}

impl SessionCache {
    pub fn new() -> Self {
        Self::default()
    }

    /// Return a clone of the cached engine for `key`, or `None`
    /// if absent. The clone shares the underlying session so
    /// `run` calls serialise on the inner mutex.
    pub fn get(&self, key: &str) -> Option<Arc<Mutex<OnnxEngine>>> {
        let guard = self.inner.lock().expect("session-cache mutex poisoned");
        guard.get(key).cloned()
    }

    /// Insert `engine` under `key`. Returns the inserted clone
    /// so the caller can use it without re-querying.
    pub fn insert(&self, key: String, engine: OnnxEngine) -> Arc<Mutex<OnnxEngine>> {
        let engine = Arc::new(Mutex::new(engine));
        let mut guard = self.inner.lock().expect("session-cache mutex poisoned");
        guard.insert(key, engine.clone());
        engine
    }

    /// Get or build an engine for `key`, calling `build` on
    /// cache miss. The build closure runs while the cache
    /// mutex is **not** held so a slow build (hundreds of ms)
    /// doesn't block concurrent reads.
    pub fn get_or_build<F>(
        &self,
        key: String,
        build: F,
    ) -> Result<Arc<Mutex<OnnxEngine>>, InferenceError>
    where
        F: FnOnce() -> Result<OnnxEngine, InferenceError>,
    {
        if let Some(hit) = self.get(&key) {
            return Ok(hit);
        }
        let engine = build()?;
        Ok(self.insert(key, engine))
    }

    /// Number of cached engines. Useful for telemetry and tests.
    pub fn len(&self) -> usize {
        self.inner
            .lock()
            .expect("session-cache mutex poisoned")
            .len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// Drop every cached engine. Used when the model registry
    /// changes (a new build of the binary ships an updated
    /// digest table).
    pub fn clear(&self) {
        self.inner
            .lock()
            .expect("session-cache mutex poisoned")
            .clear();
    }
}

/// The cache key for a builtin model: `"{kind}:{sha256}"`.
/// Including the kind in the key guards against the unlikely
/// event that two graphs share a digest.
pub fn builtin_cache_key(model: &BuiltinModel) -> String {
    format!("builtin:{}:{}", kind_label(model.kind), model.sha256)
}

/// The cache key for a catalog model: `"{kind}:{sha256}"`.
/// Same shape as the builtin key so the cache treats them
/// uniformly.
pub fn catalog_cache_key(model: &CatalogModel) -> String {
    format!("catalog:{}:{}", kind_label(model.kind), model.sha256)
}

fn kind_label(kind: BuiltinInputKind) -> &'static str {
    match kind {
        BuiltinInputKind::ImageOnly => "image",
        BuiltinInputKind::Strength => "strength",
        BuiltinInputKind::Threshold => "threshold",
        BuiltinInputKind::Mask => "mask",
    }
}

