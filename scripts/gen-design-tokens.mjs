// Generates src-vite/src/assets/tokens.css from docs/DESIGN.md frontmatter
// (colors / typography / rounded / spacing). Run: node scripts/gen-design-tokens.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const md = readFileSync(join(root, "docs/DESIGN.md"), "utf8");
const fm = md.split("---")[1];

const unquote = (v) => v.replace(/^['"]|['"]$/g, "");

const sections = {};
let section = null;
let sub = null;
for (const raw of fm.split("\n")) {
  if (!raw.trim()) continue;
  if (!raw.startsWith(" ") && raw.endsWith(":")) {
    section = raw.slice(0, -1).trim();
    sections[section] = {};
    sub = null;
    continue;
  }
  if (!section) continue;
  if (raw.startsWith("    ") && sub) {
    const m = raw.trim().match(/^([\w-]+):\s*(.+)$/);
    if (m) sections[section][sub][m[1]] = unquote(m[2]);
    continue;
  }
  if (raw.startsWith("  ") && !raw.startsWith("    ")) {
    const m = raw.trim().match(/^([\w-]+):\s*(.*)$/);
    if (!m) continue;
    if (m[2] === "") {
      sub = m[1];
      sections[section][sub] = {};
    } else {
      sub = null;
      sections[section][m[1]] = unquote(m[2]);
    }
  }
}

const colors = sections.colors || {};
const spacing = sections.spacing || {};
const rounded = sections.rounded || {};
const typo = sections.typography || {};

const lines = [];
lines.push("/* Generated by scripts/gen-design-tokens.mjs from docs/DESIGN.md. Do not edit by hand. */");
lines.push("");
lines.push(":root {");
for (const [k, v] of Object.entries(colors)) lines.push(`  --${k}: ${v};`);
lines.push("");
for (const [k, v] of Object.entries(spacing)) lines.push(`  --sp-${k}: ${v};`);
lines.push("");
for (const [k, v] of Object.entries(rounded)) lines.push(`  --radius-${k === "DEFAULT" ? "default" : k}: ${v};`);
lines.push("");
lines.push('  --font-display: "Geist", -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;');
lines.push('  --font-body: "Inter", -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;');
lines.push('  --font-data: "Space Grotesk", "JetBrains Mono", monospace;');
lines.push('  --font-mono: "JetBrains Mono", "Space Grotesk", monospace;');
for (const [k, v] of Object.entries(typo)) {
  if (v.fontSize) lines.push(`  --text-${k}: ${v.fontSize};`);
}
lines.push("}");
lines.push("");
lines.push("@theme {");
for (const [k, v] of Object.entries(colors)) lines.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(rounded)) lines.push(`  --radius-${k === "DEFAULT" ? "default" : k.toLowerCase()}: ${v};`);
lines.push("}");
lines.push("");

const out = join(root, "src-vite/src/assets/tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${Object.keys(colors).length} colors, ${Object.keys(spacing).length} spacing, ${Object.keys(rounded).length} radius, ${Object.keys(typo).length} type)`);
